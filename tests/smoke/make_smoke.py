# -*- coding: utf-8 -*-
"""Дымовая фича под ЛЮБУЮ конфигурацию: через MCP 1С выбирается справочник, который пользователь тестов может
просматривать и у которого список открывается автоматической формой (заголовок — «Представление списка» или синоним,
таблица — «Список»), и пишется features/01_smoke_open_list.feature.

    python make_smoke.py                     # выбрать сам (сначала общие: Валюты, Организации, Контрагенты, ...)
    python make_smoke.py --catalog Склады    # заданный справочник (если выбранный не открывается списком)

Зачем генерация: комплект не знает, какая конфигурация в базе проекта (типовая на БСП, отраслевая, самописная); имена
форм и элементов берутся из самой базы, а не из памяти. Дальше фичи пишутся под реальные формы — имена элементов из
vac.py get_form_analysis '{"format":"elements"}'.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "scripts"))
sys.path.insert(0, str(HERE.parents[1] / "scripts" / "mcp1c"))
from mcp1c import run_code  # noqa: E402

PICK = """
Имена = СтрРазделить("&ИМЕНА", ",", Ложь);
ТолькоИнтерфейс = &ТОЛЬКОИНТЕРФЕЙС;
// справочники из состава подсистем командного интерфейса: их пользователь открывает из разделов — список
// открывается штатно (служебные справочники, например присоединенные файлы БСП, подменяют форму в модуле менеджера)
ВИнтерфейсе = Новый Соответствие;
Подсистемы = Новый Массив;
Для Каждого П Из Метаданные.Подсистемы Цикл
	Подсистемы.Добавить(П);
КонецЦикла;
Индекс = 0;
Пока Индекс < Подсистемы.Количество() Цикл
	П = Подсистемы[Индекс];
	Индекс = Индекс + 1;
	Если Не П.ВключатьВКомандныйИнтерфейс Тогда
		Продолжить;
	КонецЕсли;
	Для Каждого Объект Из П.Состав Цикл
		ВИнтерфейсе.Вставить(Объект, Истина);
	КонецЦикла;
	Для Каждого Вложенная Из П.Подсистемы Цикл
		Подсистемы.Добавить(Вложенная);
	КонецЦикла;
КонецЦикла;
Найденные = Новый Массив;
Для Каждого МД Из Метаданные.Справочники Цикл
	Если Имена.Количество() > 0 И Имена.Найти(МД.Имя) = Неопределено Тогда
		Продолжить;
	КонецЕсли;
	Если ТолькоИнтерфейс И (ВИнтерфейсе.Получить(МД) = Неопределено Или МД.Владельцы.Количество() > 0) Тогда
		Продолжить;
	КонецЕсли;
	Если Не ПравоДоступа("Просмотр", МД) Тогда
		Продолжить;
	КонецЕсли;
	Заголовок = МД.ПредставлениеСписка;
	Если Не ЗначениеЗаполнено(Заголовок) Тогда
		Заголовок = МД.Синоним;
	КонецЕсли;
	Если Не ЗначениеЗаполнено(Заголовок) Тогда
		Продолжить;
	КонецЕсли;
	Найденные.Добавить(Новый Структура("имя, заголовок, автоформа", МД.Имя, Заголовок,
		МД.ОсновнаяФормаСписка = Неопределено));
	Если Найденные.Количество() >= 200 Тогда
		Прервать;
	КонецЕсли;
КонецЦикла;
Результат = Найденные;
"""


# справочники, которые есть почти во всех типовых (БП, УТ, КА, ERP, УНФ, ЗУП) и открываются списком из разделов
COMMON = ["Валюты", "Организации", "Контрагенты", "Номенклатура", "Склады", "ЕдиницыИзмерения", "Банки",
          "ФизическиеЛица", "Подразделения", "ВидыНоменклатуры", "Должности"]
# служебные справочники, список которых не открывается сам по себе (БСП: «Список присоединенных файлов можно посмотреть
# только в форме объекта-владельца» — модальное окно, дымовой тест на нем и упал при проверке комплекта)
SKIP = ("ПрисоединенныеФайлы", "Удалить", "удалить", "Версии", "Служебн", "Настройки")


def choose(found: list[dict]) -> dict | None:
    by_name = {c["имя"]: c for c in found}
    for name in COMMON:
        if name in by_name:
            return by_name[name]
    usable = [c for c in found if not any(s in c["имя"] for s in SKIP)]
    auto = [c for c in usable if c["автоформа"]]
    return (auto or usable or [None])[0]


def stem(title: str) -> str:
    """Основа первого значимого слова: «Валюты» -> «Валю» (совпадет с «Валюта», «Валюты»), «Склады и магазины» ->
    «Скла» (ERP при пустом списке открыл «Склад (создание)»)."""
    words = re.findall(r"[А-Яа-яЁёA-Za-z]+", title) or [title]
    word = next((w for w in words if len(w) >= 4), max(words, key=len))
    return word[:-2] if len(word) > 5 else word


def query(names: list[str], only_ui: bool) -> list[dict]:
    code = PICK.replace("&ИМЕНА", ",".join(names)).replace("&ТОЛЬКОИНТЕРФЕЙС", "Истина" if only_ui else "Ложь")
    return run_code(code, timeout=120, retries=1) or []


def main() -> int:
    name = sys.argv[sys.argv.index("--catalog") + 1] if "--catalog" in sys.argv else ""
    if name:
        found = query([name], only_ui=False)
    else:
        # сначала общие справочники типовых (в самописной конфигурации их может не быть), затем — из разделов
        found = query(COMMON, only_ui=False) + query([], only_ui=True)
    pick = choose(found)
    if not pick:
        print(f"нет подходящего справочника{' ' + name if name else ''} — задать --catalog <Имя>")
        return 1
    # заголовок окна — шаблон по основе первого слова заголовка: типовые формы бывают «умными» (ERP по
    # e1cib/list/Справочник.Валюты открыл форму элемента «руб. (Валюта)», по пустому списку складов — «Склад
    # (создание)»: точный заголовок списка не совпадал);
    # имя таблицы известно только у автоматической формы
    title = "*" + stem(pick["заголовок"]) + "*"
    check_table = ('    И элемент формы с именем "Список" присутствует на форме\n' if pick["автоформа"]
                   else "    # форма списка своя: имя таблицы — vac.py get_form_analysis '{\"format\":\"elements\"}'\n")
    text = f"""# language: ru
# encoding: utf-8
# @smoke
# Дымовой тест пары Vanessa (сгенерирован make_smoke.py): клиент тестирования подключен, открывается список
# справочника «{pick['заголовок']}» ({pick['имя']}, форма списка {'автоматическая' if pick['автоформа'] else 'своя'}), окна закрываются.
Функционал: Дымовой тест клиента тестирования
  Контекст:
    И я закрываю все окна клиентского приложения
    И я активизирую TestClient "Этот клиент"

  Сценарий: S-01 открыть список справочника
    Дано Я открываю навигационную ссылку "e1cib/list/Справочник.{pick['имя']}"
    Тогда открылось окно "{title}"
{check_table}    # СКРИН: s-01 | Список «{pick['заголовок']}» в клиенте тестирования
    И я закрываю все окна клиентского приложения
"""
    out = HERE / "features" / "01_smoke_open_list.feature"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(json.dumps({"файл": str(out), **pick}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
